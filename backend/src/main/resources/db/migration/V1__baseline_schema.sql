    INDEX idx_kb_category (category),
    INDEX idx_kb_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE kb_article_tags (
    article_id BIGINT NOT NULL,
