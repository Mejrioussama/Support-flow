    INDEX idx_attachment_ticket (ticket_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE ticket_history (
    id BIGINT NOT NULL AUTO_INCREMENT,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    version BIGINT,
    action VARCHAR(50) NOT NULL,
    field_name VARCHAR(50),
    old_value VARCHAR(500),
    new_value VARCHAR(500),
    description VARCHAR(500),
    performed_by VARCHAR(100),
    ip_address VARCHAR(45),
    user_agent VARCHAR(255),
    change_type VARCHAR(20),
    ticket_id BIGINT NOT NULL,
    user_id BIGINT,
    PRIMARY KEY (id),
    CONSTRAINT fk_ticket_history_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id),
    CONSTRAINT fk_ticket_history_user FOREIGN KEY (user_id) REFERENCES users (id),
    INDEX idx_history_ticket (ticket_id),
    INDEX idx_history_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE notifications (
    id BIGINT NOT NULL AUTO_INCREMENT,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    version BIGINT,
    title VARCHAR(200) NOT NULL,
    message TEXT,
    type VARCHAR(30),
    icon VARCHAR(50),
    link VARCHAR(500),
    sla_percentage INT,
    action_required BIT,
    suggested_actions VARCHAR(1000),
    recommended_agent VARCHAR(200),
    recommended_agent_id BIGINT,
    is_read BIT,
    read_at DATETIME(6),
    ticket_reference VARCHAR(20),
