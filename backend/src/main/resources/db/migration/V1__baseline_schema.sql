CREATE TABLE escalation_events (
    id BIGINT NOT NULL AUTO_INCREMENT,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    version BIGINT,
    ticket_id BIGINT NOT NULL,
    from_level INT NOT NULL,
    to_level INT NOT NULL,
    reason VARCHAR(30) NOT NULL,
    triggered_by VARCHAR(10) NOT NULL,
    from_agent_id BIGINT,
    to_agent_id BIGINT,
    description VARCHAR(500),
    sla_percent_at_escalation FLOAT(53),
    was_blocked BIT,
    PRIMARY KEY (id),
    CONSTRAINT fk_escalation_events_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id),
    CONSTRAINT fk_escalation_events_from_agent FOREIGN KEY (from_agent_id) REFERENCES users (id),
    CONSTRAINT fk_escalation_events_to_agent FOREIGN KEY (to_agent_id) REFERENCES users (id),
    INDEX idx_esc_event_ticket (ticket_id),
    INDEX idx_esc_event_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE escalation_policies (
    id BIGINT NOT NULL AUTO_INCREMENT,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    version BIGINT,
    client_id BIGINT,
    policy_name VARCHAR(100),
    level1_threshold INT,
    level2_threshold INT,
    level3_delay_minutes INT,
    stuck_assigned_minutes INT,
    max_escalations INT,
